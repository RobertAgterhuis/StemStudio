"""Generate ``render-vectors.json`` (contract render-vectors 1.0.0, feature 007).

Pure Python (standard library only). The file is shared by three consumers so that they cannot
drift: the C# ``RenderPlanner`` (backend), the TypeScript gate helpers of the audio engine and
the Python mixing law of the worker renderer (``render/mixing.py``). qa additionally checks the
pan matrices against Chromium's ``StereoPannerNode`` (research.md E-05).

Usage (from the repository root)::

    python specs/007-export-library/contracts/generate_render_vectors.py          # rewrite
    python specs/007-export-library/contracts/generate_render_vectors.py --check  # verify

Formulas (data-model.md 3 and 4.3):

* Pan of a stereo input ``(L, R)`` with pan ``p`` (Web Audio StereoPannerNode):
  ``p <= 0``: ``theta = (p + 1) * pi / 2``, ``L' = L + R * cos(theta)``, ``R' = R * sin(theta)``;
  ``p > 0``: ``theta = p * pi / 2``, ``L' = L * cos(theta)``, ``R' = R + L * sin(theta)``.
  ``matrix[out][in]`` with rows ``(L', R')`` and columns ``(L, R)``, rounded to 1e-9.
* Gate rule v2: a standard stem is hidden when its parent is expanded; a detail channel
  ``<p>.<d>`` is hidden when ``p`` is not expanded. ``anySolo`` = any non-hidden channel with
  ``solo``. ``gate = 0`` when hidden or muted, or when ``anySolo`` and the channel is not soloed.
* Plan: ``channels = null`` (mode ``mix``) takes every channel with gate 1 at its fader volume and
  pan; an explicit list takes exactly those channels (mute, solo and hidden ignored); mode ``raw``
  uses gain 1, pan 0 and master 1. Channels with gain 0 are dropped; an empty plan is the error
  ``nothing-to-export``. Inputs are listed in mixer order: standard stems in catalogue order,
  then detail stems per parent in catalogue order and in the track's stem order.
* Contents text: channel ids joined by " + " and ", raw" / ", mixed"; above 4 channels
  "<n> channels, raw|mixed".
"""

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

VERSION = "1.0.0"
TARGET = Path(__file__).with_name("render-vectors.json")
STEMS = ("vocals", "drums", "bass", "guitar", "piano", "other")
SIX = list(STEMS)
FOUR = ["vocals", "drums", "bass", "other"]
TRACK_ID = "0b7e4c1a-9d2f-4e8b-a1c3-5f6e7d8c9b0a"
DEFAULT_VOLUME = 0.8
PANS = (-1.0, -0.5, -0.4, 0.0, 0.25, 0.5, 1.0)
MAX_LISTED = 4
DESCRIPTION = (
    "Shared vectors of feature 007 (generated by generate_render_vectors.py; do not edit)."
)

Json = dict[str, Any]


def pan_matrix(pan: float) -> list[list[float]]:
    """Return the 2 x 2 StereoPannerNode matrix ``[[LL, LR], [RL, RR]]`` for ``pan``."""
    if pan <= 0:
        theta = (pan + 1) * math.pi / 2
        rows = [[1.0, math.cos(theta)], [0.0, math.sin(theta)]]
    else:
        theta = pan * math.pi / 2
        rows = [[math.cos(theta), 0.0], [math.sin(theta), 1.0]]
    return [[_round(value) for value in row] for row in rows]


def _round(value: float) -> float:
    rounded = round(value, 9)
    return 0.0 if rounded == 0 else rounded


def _channel_order(track: Json) -> list[str]:
    """Every channel of the track in mixer order."""
    split: dict[str, list[str]] = track.get("split", {})
    details = [f"{p}.{d}" for p in STEMS if p in split for d in split[p]]
    return [s for s in STEMS if s in track["stems"]] + details


def _settings(mix: Json, channel: str) -> Json:
    """Fader, pan, mute and solo of ``channel`` (defaults when the mix has no entry)."""
    if "." in channel:
        parent, stem = channel.split(".")
        found = [
            c for c in mix.get("detailChannels", []) if (c["parent"], c["stem"]) == (parent, stem)
        ]
    else:
        found = [c for c in mix.get("channels", []) if c["stem"] == channel]
    default = {"volume": DEFAULT_VOLUME, "pan": 0.0, "mute": False, "solo": False}
    return {**default, **found[0]} if found else default


def _hidden(mix: Json, channel: str) -> bool:
    expanded = mix.get("expanded", [])
    if "." in channel:
        return channel.partition(".")[0] not in expanded
    return channel in expanded


def _audible(track: Json, mix: Json) -> list[str]:
    """Channels with gate 1 (gate rule v2)."""
    visible = [c for c in _channel_order(track) if not _hidden(mix, c)]
    any_solo = any(_settings(mix, c)["solo"] for c in visible)
    return [
        c
        for c in visible
        if not _settings(mix, c)["mute"] and (not any_solo or _settings(mix, c)["solo"])
    ]


def _path(channel: str) -> str:
    if "." in channel:
        parent, stem = channel.split(".")
        return f"tracks/{TRACK_ID}/detail/{parent}/{stem}.flac"
    return f"tracks/{TRACK_ID}/stems/{channel}.flac"


def _input(channel: str, gain: float, pan: float) -> Json:
    return {"channelId": channel, "path": _path(channel), "gain": gain, "pan": pan}


def plan(case: Json) -> Json:
    """Expected render plan (or error) of one gate case."""
    track, mix, listed = case["track"], case["mix"], case["channels"]
    order = _channel_order(track)
    chosen = _audible(track, mix) if listed is None else [c for c in order if c in listed]
    if case["mode"] == "raw":
        inputs = [_input(c, 1.0, 0.0) for c in chosen]
        master = 1.0
    else:
        inputs = [_input(c, _settings(mix, c)["volume"], _settings(mix, c)["pan"]) for c in chosen]
        master = mix["masterVolume"]
    inputs = [i for i in inputs if i["gain"] > 0]
    if not inputs:
        return {"error": "nothing-to-export"}
    return {"masterGain": master, "inputs": inputs, "contents": _contents(case["mode"], inputs)}


def _contents(mode: str, inputs: list[Json]) -> str:
    word = "raw" if mode == "raw" else "mixed"
    if len(inputs) > MAX_LISTED:
        return f"{len(inputs)} channels, {word}"
    return " + ".join(i["channelId"] for i in inputs) + f", {word}"


def _ch(stem: str, volume: float = DEFAULT_VOLUME, pan: float = 0.0, *flags: str) -> Json:
    return {
        "stem": stem,
        "volume": volume,
        "pan": pan,
        "mute": "mute" in flags,
        "solo": "solo" in flags,
    }


def _dch(parent: str, stem: str, volume: float = DEFAULT_VOLUME, *flags: str) -> Json:
    return {"parent": parent, **_ch(stem, volume, 0.0, *flags)}


DRUMS_SPLIT = {"drums": ["kick", "snare", "rest"]}


def _case(
    name: str,
    description: str,
    track: Json,
    mix: Json,
    mode: str = "mix",
    channels: list[str] | None = None,
) -> Json:
    case = {
        "name": name,
        "description": description,
        "trackId": TRACK_ID,
        "track": track,
        "mix": mix,
        "mode": mode,
        "channels": channels,
    }
    return {**case, "expected": plan(case)}


def _mix(
    master: float = 0.7,
    channels: list[Json] | None = None,
    details: list[Json] | None = None,
    expanded: list[str] | None = None,
) -> Json:
    return {
        "masterVolume": master,
        "channels": channels or [],
        "detailChannels": details or [],
        "expanded": expanded or [],
    }


def gate_cases() -> list[Json]:
    """The binding gate cases (contracts/DELTA.md 4)."""
    six = {"stems": SIX, "split": {}}
    split = {"stems": SIX, "split": DRUMS_SPLIT}
    return [
        _case(
            "no-solo",
            "No solo: every unmuted channel at its fader and pan",
            six,
            _mix(0.7, [_ch("guitar", 0.8, 0.0, "mute"), _ch("bass", 0.9, -0.25)]),
        ),
        _case(
            "solo-standard",
            "Solo on one standard stem: only that stem",
            six,
            _mix(1.0, [_ch("bass", 0.6, 0.5, "solo")]),
        ),
        _case(
            "solo-hidden-ignored",
            "Solo on a hidden channel (expanded parent) is ignored",
            split,
            _mix(0.9, [_ch("drums", 0.8, 0.0, "solo")], [], ["drums"]),
        ),
        _case(
            "mute-and-solo",
            "Mute wins over solo on the same channel; another solo still counts",
            six,
            _mix(1.0, [_ch("vocals", 0.8, 0.0, "mute", "solo"), _ch("bass", 0.7, 0.0, "solo")]),
        ),
        _case(
            "expanded-muted-detail",
            "Expanded parent: detail channels replace it; a muted detail is left out",
            split,
            _mix(
                0.8,
                [_ch("guitar", 0.5, 0.4)],
                [_dch("drums", "snare", 0.8, "mute"), _dch("drums", "kick", 0.95)],
                ["drums"],
            ),
        ),
        _case(
            "collapsed-details-hidden",
            "Collapsed parent: its detail channels are hidden, the parent plays",
            split,
            _mix(1.0, [], [_dch("drums", "kick", 0.9, "solo")], []),
        ),
        _case(
            "explicit-selection",
            "Selected channels ignore mute, solo and hidden",
            split,
            _mix(
                0.75,
                [_ch("guitar", 0.6, -0.5, "mute"), _ch("bass", 0.8, 0.0, "solo")],
                [_dch("drums", "kick", 0.9)],
                [],
            ),
            "mix",
            ["drums.kick", "guitar"],
        ),
        _case(
            "raw-single",
            "Raw mode: gain 1, pan 0, master 1",
            six,
            _mix(0.5, [_ch("drums", 0.3, 0.7, "mute")]),
            "raw",
            ["drums"],
        ),
        _case(
            "raw-detail",
            "Raw mode with a detail stem, inputs in mixer order",
            split,
            _mix(0.5),
            "raw",
            ["drums.kick", "vocals"],
        ),
        _case(
            "gain-zero-dropped",
            "A channel with fader 0 is dropped",
            six,
            _mix(1.0, [_ch("bass", 0.0)]),
            "mix",
            ["vocals", "bass"],
        ),
        _case(
            "nothing-audible",
            "Everything muted: nothing to export",
            {"stems": FOUR, "split": {}},
            _mix(1.0, [_ch(s, 0.8, 0.0, "mute") for s in FOUR]),
        ),
        _case(
            "four-stem-model",
            "htdemucs track (4 stems), no solo",
            {"stems": FOUR, "split": {}},
            _mix(1.0, [_ch("other", 0.4, 1.0)]),
        ),
    ]


def document() -> Json:
    """The whole ``render-vectors.json`` document."""
    return {
        "version": VERSION,
        "description": DESCRIPTION,
        "gate": gate_cases(),
        "pan": [{"pan": p, "matrix": pan_matrix(p)} for p in PANS],
    }


def render() -> str:
    """The document as written to disk (2-space indent, trailing newline)."""
    return json.dumps(document(), indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    """Write the vectors, or with ``--check`` verify that the file is up to date."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    args = parser.parse_args(argv)
    if args.check:
        return 0 if TARGET.read_text(encoding="utf-8") == render() else 1
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
