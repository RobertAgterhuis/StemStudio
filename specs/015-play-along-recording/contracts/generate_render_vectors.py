"""Generate ``render-vectors.json`` 1.1.0 (feature 015): the 007 vectors 1.0.0 unchanged plus the take cases.

Pure Python (standard library only). The 007 generator (``specs/007-export-library/contracts/
generate_render_vectors.py``) stays the single source of the 1.0.0 cases and formulas; this script
loads it and appends the ``take`` gate cases of contracts/DELTA.md 5 (data-model 2.7). Consumers move
from the 007 file to this one in the task that implements the take channel (audio-engine T018/T019,
backend export planner in US6); until then they keep reading 1.0.0, which this file contains unchanged.

Usage (from the repository root)::

    python -I specs/015-play-along-recording/contracts/generate_render_vectors.py          # rewrite
    python -I specs/015-play-along-recording/contracts/generate_render_vectors.py --check  # verify

Take rules (binding):

* A case with a take has ``take = { takeId, assetId, name, startSample, lengthSamples }`` and, in mix
  mode, ``mix.take = { takeId, volume, pan, mute, solo }`` (``MixSettings.take``). The take channel
  ``take`` is an audible-level channel: never hidden, part of ``anySolo``, gated like a stem. It is
  listed **last** in mixer order; its input path is ``assets/<assetId>/audio.flac`` (the padded FLAC,
  so it aligns at song sample 0 like the stems).
* Raw mode with ``channels: ["take"]``: gain 1, pan 0, master 1, and ``expected.range`` = the take's
  span ``[startSample / 44100, (startSample + lengthSamples) / 44100]`` (rounded to 1e-9).
* ``take`` listed or soloed without a take in the case: the error ``take-required``.
* Contents: the take's name, then `` - `` and the 007 contents of the other inputs; only the take:
  ``"<name>, raw|mixed"``. ``expected.sourceAssetIds`` = ``[assetId]`` when the take is an input.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

VERSION = "1.1.0"
TARGET = Path(__file__).with_name("render-vectors.json")
BASE_GENERATOR = Path(__file__).resolve().parents[2] / "007-export-library" / "contracts" / "generate_render_vectors.py"
SAMPLE_RATE = 44100
TAKE = {
    "takeId": "1c2d3e4f-5a6b-4c7d-8e9f-0a1b2c3d4e5f",
    "assetId": "6e5d4c3b-2a1f-4e0d-9c8b-7a6f5e4d3c2b",
    "name": "Take 2",
    "startSample": 1323000,
    "lengthSamples": 882000,
}
DESCRIPTION = (
    "Shared vectors of features 007 and 015 (generated by the 015 generate_render_vectors.py; do not edit). "
    "1.1.0 = the 1.0.0 cases unchanged plus the take cases."
)

Json = dict[str, Any]


def _base() -> ModuleType:
    """The 007 generator as a module (source of the 1.0.0 cases and formulas)."""
    spec = importlib.util.spec_from_file_location("render_vectors_007", BASE_GENERATOR)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load {BASE_GENERATOR}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


V007 = _base()


def _take_input(gain: float, pan: float) -> Json:
    return {"channelId": "take", "path": f"assets/{TAKE['assetId']}/audio.flac", "gain": gain, "pan": pan}


def _take_settings(mix: Json) -> Json | None:
    return mix.get("take")


def _take_audible(mix: Json, any_solo: bool) -> bool:
    take = _take_settings(mix)
    return take is not None and not take["mute"] and (not any_solo or take["solo"])


def _any_solo(track: Json, mix: Json) -> bool:
    visible = [c for c in V007._channel_order(track) if not V007._hidden(mix, c)]
    take = _take_settings(mix)
    return any(V007._settings(mix, c)["solo"] for c in visible) or bool(take and take["solo"])


def _stem_inputs(case: Json, any_solo: bool) -> list[Json]:
    """007 inputs, with the take's solo taking part in ``anySolo``."""
    track, mix, listed = case["track"], case["mix"], case["channels"]
    order = V007._channel_order(track)
    if listed is None:
        visible = [c for c in order if not V007._hidden(mix, c)]
        chosen = [c for c in visible if not V007._settings(mix, c)["mute"] and (not any_solo or V007._settings(mix, c)["solo"])]
    else:
        chosen = [c for c in order if c in listed]
    if case["mode"] == "raw":
        return [V007._input(c, 1.0, 0.0) for c in chosen]
    return [V007._input(c, V007._settings(mix, c)["volume"], V007._settings(mix, c)["pan"]) for c in chosen]


def _with_take(case: Json, any_solo: bool) -> list[Json]:
    """The take input (or nothing) for a case that has a take."""
    listed, mix = case["channels"], case["mix"]
    if case["mode"] == "raw":
        return [_take_input(1.0, 0.0)] if listed and "take" in listed else []
    take = _take_settings(mix)
    wanted = ("take" in listed) if listed is not None else _take_audible(mix, any_solo)
    return [_take_input(take["volume"], take["pan"])] if take and wanted else []


def plan(case: Json) -> Json:
    """Expected render plan (or error) of one take case."""
    mix, listed = case["mix"], case["channels"]
    has_take = case.get("take") is not None and (case["mode"] == "raw" or _take_settings(mix) is not None)
    if not has_take and ((listed and "take" in listed) or (_take_settings(mix) or {}).get("solo")):
        return {"error": "take-required"}
    any_solo = _any_solo(case["track"], mix)
    inputs = [i for i in _stem_inputs(case, any_solo) + _with_take(case, any_solo) if i["gain"] > 0]
    if not inputs:
        return {"error": "nothing-to-export"}
    master = 1.0 if case["mode"] == "raw" else mix["masterVolume"]
    expected: Json = {"masterGain": master, "inputs": inputs, "contents": _contents(case["mode"], inputs)}
    if any(i["channelId"] == "take" for i in inputs):
        expected["sourceAssetIds"] = [TAKE["assetId"]]
    if case["mode"] == "raw" and listed == ["take"]:
        start, length = TAKE["startSample"], TAKE["lengthSamples"]
        expected["range"] = {"start": V007._round(start / SAMPLE_RATE), "end": V007._round((start + length) / SAMPLE_RATE)}
    return expected


def _contents(mode: str, inputs: list[Json]) -> str:
    others = [i for i in inputs if i["channelId"] != "take"]
    if len(others) == len(inputs):
        return V007._contents(mode, inputs)
    if not others:
        return f"{TAKE['name']}, {'raw' if mode == 'raw' else 'mixed'}"
    return f"{TAKE['name']} - {V007._contents(mode, others)}"


def _take_mix(volume: float = 1.0, pan: float = 0.0, *flags: str) -> Json:
    return {"takeId": TAKE["takeId"], "volume": volume, "pan": pan, "mute": "mute" in flags, "solo": "solo" in flags}


def _case(name: str, description: str, mix: Json, mode: str = "mix", channels: list[str] | None = None, take: bool = True) -> Json:
    case = {
        "name": name,
        "description": description,
        "trackId": V007.TRACK_ID,
        "track": {"stems": V007.SIX, "split": {}},
        "mix": mix,
        "mode": mode,
        "channels": channels,
        "take": dict(TAKE) if take else None,
    }
    return {**case, "expected": plan(case)}


def take_cases() -> list[Json]:
    """The binding take cases (contracts/DELTA.md 5)."""
    ch, mix = V007._ch, V007._mix
    return [
        _case("take-no-solo", "Take strip without solo: every unmuted stem, then the take last", {**mix(0.8, [ch("bass", 0.9, -0.25)]), "take": _take_mix(0.9, 0.3)}),
        _case("take-solo-only", "Only the take soloed: the take alone", {**mix(1.0), "take": _take_mix(0.7, 0.0, "solo")}),
        _case("take-muted", "Take muted: the stems only, no take input", {**mix(1.0, [ch("other", 0.5)]), "take": _take_mix(1.0, 0.0, "mute")}),
        _case(
            "take-compare-my-take",
            "Compare 'My take' as sent by the frontend: the part's stem muted, the take plays",
            {**mix(1.0, [ch("guitar", 0.8, 0.0, "mute")]), "take": _take_mix(1.0, -0.2)},
        ),
        _case("take-explicit-selection", "Selected channels take and bass: mixer order, take last", {**mix(0.9, [ch("bass", 0.6)]), "take": _take_mix(0.8)}, "mix", ["take", "bass"]),
        _case("take-raw", "Raw take: gain 1, pan 0, master 1, range = the take's span", mix(0.5), "raw", ["take"]),
        _case("take-volume-zero", "Take fader at 0 is dropped", {**mix(1.0, [ch(s, 0.8, 0.0, "mute") for s in ("vocals", "drums", "guitar", "piano", "other")]), "take": _take_mix(0.0)}),
        _case("take-required", "Channel take listed without a take", mix(1.0), "mix", ["take", "bass"], take=False),
    ]


def document() -> Json:
    """The whole 1.1.0 document."""
    base = V007.document()
    return {"version": VERSION, "description": DESCRIPTION, "gate": base["gate"] + take_cases(), "pan": base["pan"]}


def render() -> str:
    """The document as written to disk (2-space indent, trailing newline)."""
    return json.dumps(document(), indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    """Write the vectors, or with ``--check`` verify that the file is up to date."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    args = parser.parse_args(argv)
    if args.check:
        return 0 if TARGET.read_text(encoding="utf-8") == render() else 1
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
