def document() -> Json:
    """The whole ``render-vectors.json`` 1.2.0 document (base sections + ``timeline``)."""
    base = load_base()
    sections = {key: value for key, value in base.items() if key not in HEADER_KEYS}
    return {
        "version": VERSION,
        "description": DESCRIPTION,
        "baseVersion": base["version"],
        **sections,
        "timeline": {
            "resolve": resolve_cases(),
            "spans": spans_cases(),
            "samples": samples_cases(),
            "clock": [clock_case()],
            "metronome": [metronome_case()],
        },
    }


def load_base() -> Json:
    """The newest available base document (015's 1.1.0, else 007's 1.0.0)."""
    path = next(p for p in BASES if p.exists())
    base: Json = json.loads(path.read_text(encoding="utf-8"))
    return base


def render() -> str:
    """The document as written to disk (2-space indent, trailing newline)."""
    return json.dumps(document(), indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    """Write the vectors, or with ``--check`` verify that the file is up to date."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the file is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.name} is out of date; run without --check", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
