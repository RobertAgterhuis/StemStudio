LINE_TOLERANCE = 0.001
MIN_REGION_SECONDS = 0.5
MAX_REGIONS = 64
MAX_REPEAT = 16
MAX_SEGMENTS = 256
MAX_TOTAL_SECONDS = 1800.0
MAX_CROSSFADE_MS = 50
DURATION = 40.0
DOWNBEATS = [round(0.5 + 2.0 * k, 6) for k in range(20)]
BEATS = [round(0.5 + 0.5 * k, 6) for k in range(79)]
SIX = ["vocals", "drums", "bass", "guitar", "piano", "other"]

Json = dict[str, Any]


def frame(seconds: float) -> int:
    """Nearest frame at 44.1 kHz (ties up)."""
    return math.floor(seconds * RATE + 0.5)


def crossfade_frames(ms: int) -> int:
    """Even crossfade length in frames for ``ms`` milliseconds."""
    return 2 * math.floor(ms * RATE / 2000 + 0.5)


def _r(value: float) -> float:
    rounded = round(value, 9)
    return 0.0 if rounded == 0 else rounded


# --- resolve (regions -> segments) -------------------------------------------------------------


def bar_lines(grid: Json, duration: float) -> list[float]:
    """Bar lines of the track: 0, downbeats before the end, the end."""
    lines: list[float] = []
    for value in [0.0, *[d for d in grid["downbeats"] if d < duration], duration]:
        if not lines or value - lines[-1] > LINE_TOLERANCE:
            lines.append(value)
    return lines


def _line_index(lines: list[float], seconds: float) -> int | None:
    for index, line in enumerate(lines):
        if abs(line - seconds) <= LINE_TOLERANCE:
            return index
    return None


def _bar_number(lines: list[float], grid: Json, index: int) -> int:
    has_pickup = bool(grid["downbeats"]) and grid["downbeats"][0] > LINE_TOLERANCE
    return index if has_pickup else index + 1


def _region_errors(index: int, region: Json, ctx: Json) -> list[Json]:
    key = f"regions[{index}]"
    start, end = region["startSeconds"], region["endSeconds"]
    errors: list[Json] = []
    if start < 0 or end > ctx["duration"] + LINE_TOLERANCE:
        errors.append({"key": f"{key}.endSeconds", "code": "outside-track"})
    if end - start < MIN_REGION_SECONDS:
        errors.append({"key": f"{key}.endSeconds", "code": "too-short"})
    if not 1 <= region["repeat"] <= MAX_REPEAT:
        errors.append({"key": f"{key}.repeat", "code": "out-of-range"})
    errors += _snap_errors(key, region, ctx)
    errors += _mute_errors(key, region, ctx)
    return errors


def _snap_errors(key: str, region: Json, ctx: Json) -> list[Json]:
    if ctx["snap"] != "bars":
        return []
    errors = []
    for field in ("startSeconds", "endSeconds"):
        if _line_index(ctx["lines"], region[field]) is None:
            errors.append({"key": f"{key}.{field}", "code": "not-on-bar-line"})
    return errors


def _mute_errors(key: str, region: Json, ctx: Json) -> list[Json]:
    mutes = region["mutes"]
    if len(set(mutes)) != len(mutes):
        return [{"key": f"{key}.mutes", "code": "duplicate"}]
    unknown = [m for m in mutes if m not in ctx["channels"]]
    return [{"key": f"{key}.mutes", "code": "unknown-channel", "channel": m} for m in unknown]


def _document_errors(doc: Json, ctx: Json) -> list[Json]:
    regions = doc["regions"]
    errors: list[Json] = []
    if not 0 <= doc["crossfadeMs"] <= MAX_CROSSFADE_MS:
        errors.append({"key": "crossfadeMs", "code": "out-of-range"})
    if ctx["snap"] == "bars" and not ctx["grid"]["downbeats"]:
        errors.append({"key": "snap", "code": "no-bars"})
    if not 1 <= len(regions) <= MAX_REGIONS:
        errors.append({"key": "regions", "code": "count"})
    if sum(r["repeat"] for r in regions) > MAX_SEGMENTS:
        errors.append({"key": "regions", "code": "too-many-segments"})
    total = sum((frame(r["endSeconds"]) - frame(r["startSeconds"])) * r["repeat"] for r in regions)
    if total > MAX_TOTAL_SECONDS * RATE:
        errors.append({"key": "regions", "code": "too-long"})
    return errors


def _bars(region: Json, ctx: Json) -> Json | None:
    if ctx["snap"] != "bars":
        return None
    first = _line_index(ctx["lines"], region["startSeconds"])
    last = _line_index(ctx["lines"], region["endSeconds"])
    assert first is not None and last is not None
    number = _bar_number(ctx["lines"], ctx["grid"], first)
    return {"first": number, "last": number + (last - first) - 1}


def _segments(doc: Json, ctx: Json) -> list[Json]:
    segments: list[Json] = []
    arranged = 0
    for index, region in enumerate(doc["regions"]):
        start, count = frame(region["startSeconds"]), frame(region["endSeconds"])
        for repeat in range(region["repeat"]):
            segments.append(
                _segment((index, repeat), region, (start, count - start, arranged), ctx)
            )
            arranged += count - start
    return segments


def _segment(ids: tuple[int, int], region: Json, frames: tuple[int, int, int], ctx: Json) -> Json:
    source_start, frame_count, arranged_start = frames
    return {
        "regionIndex": ids[0],
        "repeatIndex": ids[1],
        "arrangedStartFrame": arranged_start,
        "sourceStartFrame": source_start,
        "frameCount": frame_count,
        "mutes": list(region["mutes"]),
        "bars": _bars(region, ctx),
    }


def resolve(case: Json) -> Json:
    """Expected resolution (or validation errors) of one ``timeline.resolve`` case."""
    doc, track = case["arrangement"], case["track"]
    ctx = {
        "duration": track["durationSeconds"],
        "grid": track["beatGrid"],
        "snap": doc["snap"],
        "channels": track["channels"],
        "lines": bar_lines(track["beatGrid"], track["durationSeconds"]),
    }
    errors = _document_errors(doc, ctx)
    for index, region in enumerate(doc["regions"]):
        errors += _region_errors(index, region, ctx)
    if errors:
        return {"errors": errors}
    return _resolved(doc, ctx)


def _resolved(doc: Json, ctx: Json) -> Json:
    segments = _segments(doc, ctx)
    total = sum(s["frameCount"] for s in segments)
    warnings = [] if ctx["grid"]["reliable"] or ctx["snap"] != "bars" else ["grid-unreliable"]
    return {
        "sampleRate": RATE,
        "crossfadeFrames": crossfade_frames(doc["crossfadeMs"]),
        "totalFrames": total,
        "durationSeconds": _r(total / RATE),
        "segments": segments,
        "warnings": warnings,
    }


# --- spans (segments -> per-channel runs) ------------------------------------------------------


def _parent(channel: str) -> str:
    return channel.split(".")[0]


def is_open(segment: Json, channel: str) -> bool:
    """Whether ``channel`` plays in ``segment`` (neither it nor its parent is muted)."""
    return channel not in segment["mutes"] and _parent(channel) not in segment["mutes"]


def contiguous(previous: Json, current: Json) -> bool:
    """Whether ``current`` continues ``previous`` in the source without a jump."""
    end: int = previous["sourceStartFrame"] + previous["frameCount"]
    return end == int(current["sourceStartFrame"])


def _run_groups(segments: list[Json], channel: str) -> list[list[int]]:
    groups: list[list[int]] = []
    for index, segment in enumerate(segments):
        if not is_open(segment, channel):
            continue
        if _continues(groups, segments, index):
            groups[-1].append(index)
        else:
            groups.append([index])
    return groups


def _continues(groups: list[list[int]], segments: list[Json], index: int) -> bool:
    """Whether open segment ``index`` extends the last run (adjacent and contiguous)."""
    if not groups or groups[-1][-1] != index - 1:
        return False
    return contiguous(segments[index - 1], segments[index])


def _fades(segments: list[Json], group: list[int], fade: int) -> tuple[bool, bool]:
    return fade > 0 and group[0] > 0, fade > 0 and group[-1] < len(segments) - 1


def _run(segments: list[Json], group: list[int], fade: int) -> Json:
    first, last = segments[group[0]], segments[group[-1]]
    fade_in, fade_out = _fades(segments, group, fade)
    lead, tail = fade // 2 * fade_in, fade // 2 * fade_out
    start = first["arrangedStartFrame"] - lead
    return {
        "firstSegment": group[0],
        "lastSegment": group[-1],
        "arrangedStartFrame": start,
        "sourceStartFrame": first["sourceStartFrame"] - lead,
        "frameCount": last["arrangedStartFrame"] + last["frameCount"] + tail - start,
        "fadeIn": fade_in,
        "fadeOut": fade_out,
    }


def runs(segments: list[Json], channel: str, fade: int) -> list[Json]:
    """Every run of ``channel`` over the timeline."""
    return [_run(segments, group, fade) for group in _run_groups(segments, channel)]


def muted_inputs(segment: Json, channels: list[str]) -> list[int]:
    """Indices of the render inputs that are muted in ``segment`` (worker ``mutedInputs``)."""
    return [i for i, channel in enumerate(channels) if not is_open(segment, channel)]


def spans(case: Json) -> Json:
    """Expected runs per channel and worker segments of one ``timeline.spans`` case."""
    segments, channels, fade = case["segments"], case["channels"], case["crossfadeFrames"]
    return {
        "runs": {channel: runs(segments, channel, fade) for channel in channels},
        "workerSegments": [
            {
                "sourceStartFrame": s["sourceStartFrame"],
                "frameCount": s["frameCount"],
                "mutedInputs": muted_inputs(s, channels),
            }
            for s in segments
        ],
    }


# --- samples (sample-exact output) -------------------------------------------------------------


def fade_gain(run: Json, offset: int, fade: int) -> float:
    """Gain of ``run`` at ``offset`` frames from its arranged start."""
    if run["fadeIn"] and offset < fade:
        return math.sin(math.pi / 2 * (offset + 0.5) / fade)
    tail = run["frameCount"] - offset
    if run["fadeOut"] and tail <= fade:
        return math.cos(math.pi / 2 * (fade - tail + 0.5) / fade)
    return 1.0


def signal(channel_index: int, n: int) -> tuple[float, float]:
    """Deterministic stereo test signal of input ``channel_index`` at source frame ``n``."""
    if channel_index == 0:
        return ((n + 1) / 128.0, 0.5 - n / 256.0)
    return (((n * 7) % 64) / 64.0 - 0.5, 0.25 * math.sin(0.3 * n))


def _source(channel_index: int, n: int, length: int) -> tuple[float, float]:
    return signal(channel_index, n) if 0 <= n < length else (0.0, 0.0)


def samples(case: Json) -> list[list[float]]:
    """Expected output frames ``[L, R]`` (gain 1, pan 0, master 1) of one samples case."""
    segments, fade = case["segments"], case["crossfadeFrames"]
    total = sum(s["frameCount"] for s in segments)
    out = [[0.0, 0.0] for _ in range(total)]
    for index, channel in enumerate(case["channels"]):
        _add_channel(out, runs(segments, channel, fade), (index, case["sourceFrames"], fade))
    return [[_r(left), _r(right)] for left, right in out]


def _add_channel(
    out: list[list[float]], channel_runs: list[Json], spec: tuple[int, int, int]
) -> None:
    for run in channel_runs:
        _add_run(out, run, spec)


def _add_run(out: list[list[float]], run: Json, spec: tuple[int, int, int]) -> None:
    index, length, fade = spec
    for offset in range(run["frameCount"]):
        t = run["arrangedStartFrame"] + offset
        if 0 <= t < len(out):
            gain = fade_gain(run, offset, fade)
            left, right = _source(index, run["sourceStartFrame"] + offset, length)
            out[t][0] += gain * left
            out[t][1] += gain * right


# --- clock and metronome -----------------------------------------------------------------------


def source_at(segments: list[Json], arranged_seconds: float) -> Json:
    """Source time and segment index heard at ``arranged_seconds`` (boundary = next segment)."""
    t = arranged_seconds * RATE
    for index, s in enumerate(segments):
        if s["arrangedStartFrame"] <= t < s["arrangedStartFrame"] + s["frameCount"]:
            source = (s["sourceStartFrame"] + t - s["arrangedStartFrame"]) / RATE
            return {
                "arrangedSeconds": arranged_seconds,
                "sourceSeconds": _r(source),
                "segmentIndex": index,
            }
    return {"arrangedSeconds": arranged_seconds, "sourceSeconds": None, "segmentIndex": None}


def clicks(segments: list[Json], grid: Json) -> list[Json]:
    """Arranged metronome clicks: each segment plays the source beats inside it."""
    result: list[Json] = []
    downbeats = set(grid["downbeats"])
    for s in segments:
        start = s["sourceStartFrame"] / RATE
        end = (s["sourceStartFrame"] + s["frameCount"]) / RATE
        shift = s["arrangedStartFrame"] / RATE - start
        result += [
            {"time": _r(b + shift), "accent": b in downbeats}
            for b in grid["beats"]
            if start <= b < end
        ]
    return result


# --- cases -------------------------------------------------------------------------------------


def _grid(reliable: bool = True, bars: bool = True) -> Json:
    return {
        "bpm": 120.0 if bars else 0.0,
        "beats": BEATS if bars else [],
        "downbeats": DOWNBEATS if bars else [],
        "beatsPerBar": 4,
        "confidence": 0.9 if reliable else 0.3,
        "reliable": reliable,
    }


def _track(grid: Json | None = None) -> Json:
    channels = [*SIX, "guitar.acoustic-guitar", "guitar.electric-guitar", "guitar.rest"]
    return {"durationSeconds": DURATION, "beatGrid": grid or _grid(), "channels": channels}


def _region(start: float, end: float, repeat: int = 1, *mutes: str) -> Json:
    return {"startSeconds": start, "endSeconds": end, "repeat": repeat, "mutes": list(mutes)}


def _doc(regions: list[Json], snap: str = "bars", crossfade_ms: int = 10) -> Json:
    return {"snap": snap, "crossfadeMs": crossfade_ms, "regions": regions}


def _resolve_case(name: str, description: str, doc: Json, track: Json | None = None) -> Json:
    case = {
        "name": name,
        "description": description,
        "track": track or _track(),
        "arrangement": doc,
    }
    case["expected"] = resolve(case)
    return case


