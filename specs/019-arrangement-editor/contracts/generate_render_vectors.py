"""Generate ``render-vectors.json`` 1.2.0 (feature 019: arrangement timelines).

Pure Python (standard library only). Version 1.2.0 is **additive** and contains 1.1.0 (CTO
allocation 2026-11-16: 015 play-along recording owns 1.1.0). Every section of the base document
is copied unchanged: the base is 015's 1.1.0
(``specs/015-play-along-recording/contracts/render-vectors.json``) when that file exists, else
007's 1.0.0 (``gate`` and ``pan``) during the parallel planning round; 019 Phase 0 regenerates on
top of the merged 1.1.0. A new ``timeline`` section is added. It is shared by four consumers so
they cannot drift (ADR-028, data-model.md 3):

* backend (C#): ``timeline.resolve`` (regions -> segments) and ``timeline.spans[*].mutedInputs``
  (region mutes -> worker input indices);
* audio engine (TS): ``timeline.spans`` (per-channel runs and fades), ``timeline.clock``
  (arranged -> source time) and ``timeline.metronome`` (arranged click times);
* worker (Python): ``timeline.spans`` and ``timeline.samples`` (sample-exact output);
* browser (qa): ``timeline.samples`` rendered by the built engine in an ``OfflineAudioContext``.

Usage (from the repository root)::

    python specs/019-arrangement-editor/contracts/generate_render_vectors.py          # rewrite
    python specs/019-arrangement-editor/contracts/generate_render_vectors.py --check  # verify

Formulas (data-model.md 3):

* ``frame(x) = floor(x * 44100 + 0.5)``; crossfade ``F = 2 * floor(ms * 44.1 / 2 + 0.5)``.
* Bar lines: ``0``, every downbeat ``< duration`` and ``duration``, deduplicated within 1 ms.
* Segments: regions in order, each repeated ``repeat`` times, laid end to end.
* Runs of a channel: maximal sequences of consecutive segments where the channel is open
  (neither it nor its parent is muted) and every inner boundary is contiguous in the source.
  A run that does not start the timeline starts ``F/2`` frames early with a fade-in; a run that
  does not end the timeline ends ``F/2`` frames late with a fade-out (``F = 0``: hard cut).
* Gains over the ``F`` fade frames ``k = 0..F-1``: in ``sin(pi/2 * (k + 0.5) / F)``, out
  ``cos(pi/2 * (k + 0.5) / F)``; source frames outside the file are silence.
"""

