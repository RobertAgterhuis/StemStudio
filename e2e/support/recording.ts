const recordingRoot = path.resolve(__dirname, '..', '..', 'tests', 'fixtures', 'recording');

/** Where a recording fixture is written (not checked: launch options are set before any test runs). */
export function recordingFixtureFile(name: RecordingFixtureName): string {
  return path.join(recordingRoot, name);
}

/**
 * Absolute path of a generated recording fixture.
 * @throws Error naming the generator command when the audio has not been generated yet.
 */
export function recordingFixturePath(name: RecordingFixtureName): string {
  const file = recordingFixtureFile(name);
  if (!existsSync(file)) {
    throw new Error(`Fixture ${name} is missing; run: cd tests/fixtures && uv run --project ../../worker python -m recording.generate_recording_fixtures`);
  }
  return file;
}

/** Launch options of a recording worker: full Chromium with `input` as the fake capture device. */
export function recordingLaunchOptions(input: RecordingFixtureName): LaunchOptions {
  return fakeMicrophoneLaunchOptions('chromium', recordingFixtureFile(input));
}

/** Records the origin of every request of the page (SC-007); read the array at the end of the test. */
export function watchOrigins(page: Page): string[] {
  const origins: string[] = [];
  page.on('request', (request) => {
    const url = new URL(request.url());
    if (url.protocol === 'http:' || url.protocol === 'https:') {
      origins.push(url.origin);
    }
  });
  return origins;
}

/** Asserts that the page talked only to the StemStudio web and API origins (recordings stay local, FR-017). */
export function expectOnlyAppOrigins(origins: readonly string[]): void {
  const allowed = new Set([new URL(webBaseUrl).origin, new URL(apiBaseUrl).origin]);
  expect([...new Set(origins)].filter((origin) => !allowed.has(origin)), 'requests to other hosts').toEqual([]);
}

/** Bit depth of a FLAC file from its STREAMINFO block (bytes 8.. after `fLaC` + block header). */
export function flacBitDepth(bytes: Buffer): number {
  expect(bytes.subarray(0, 4).toString('latin1'), 'FLAC magic').toBe('fLaC');
  const streamInfo = 8;
  // STREAMINFO: 10 bytes of block sizes, then 20 bits rate, 3 bits channels-1, 5 bits bits-1.
  const packed = bytes.readUInt32BE(streamInfo + 10);
  return ((packed >>> 4) & 0x1f) + 1;
}
